-- LuxeChat MVP schema: authenticated community lobby.
-- Run in Supabase SQL Editor. Do not use a service-role key in the Android app.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender_name text not null check (char_length(sender_name) between 1 and 40),
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists messages_created_at_idx on public.messages (created_at desc);
alter table public.messages enable row level security;

-- Any signed-in user can read lobby messages.
drop policy if exists "Authenticated users can read messages" on public.messages;
create policy "Authenticated users can read messages"
  on public.messages for select to authenticated using (true);

-- Users may only insert messages under their own auth user ID.
drop policy if exists "Users can send as themselves" on public.messages;
create policy "Users can send as themselves"
  on public.messages for insert to authenticated
  with check (auth.uid() = sender_id);

-- No update/delete policies are intentionally provided in this MVP.
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

